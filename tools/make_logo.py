"""MIASMORA -- the splash logo and the promotional image, from the font.

Writes:
  src/logo_miasmora.h                 the logo's shape and its glow as 4-bit
                                      alpha (16 levels), cropped to their boxes
  docs/MIASMORA_promo_1280x960.png    the same design for M5Burner / GitHub

The font (UnifrakturMaguntia, SIL Open Font License 1.1) stays in
tools/fonts/; the firmware only gets the pixels. The same input always gives
the same output (no randomness without a fixed seed).

Usage (from the project folder; Pillow is needed):
  python tools/make_logo.py
"""
import os
import random

from PIL import Image, ImageDraw, ImageFilter, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FONT = os.path.join(HERE, "fonts", "UnifrakturMaguntia-Book.ttf")
TEXT = "Miasmora"

# --- the device's splash ----------------------------------------------------
SCREEN_W, SCREEN_H = 240, 135
LOGO_WIDTH = 212        # the logo's width on the 240 px screen
LOGO_CY = 52            # its vertical centre (a little above the middle: the subtitle goes below)
SUPER = 8               # rendered this much larger, then reduced (smooth edges)
GLOW_RADIUS = 4         # px on the device
GLOW_GAIN = 1.8         # the blurred shape is brightened (it would be faint otherwise)

# --- the colours (src/ui/ui.cpp uiInitColors) ---------------------------------
C_BG = (6, 6, 8)
C_ACC2 = (225, 70, 55)  # the old splash's title colour: the logo
C_DIM = (120, 116, 112) # the subtitle


def render_text(width):
    """The text as an 8-bit alpha image, `width` px wide, cropped to its ink."""
    size = 100
    font = ImageFont.truetype(FONT, size * SUPER)
    l, t, r, b = font.getbbox(TEXT)
    scale = width * SUPER / (r - l)
    font = ImageFont.truetype(FONT, round(size * SUPER * scale))
    l, t, r, b = font.getbbox(TEXT)
    pad = 2 * SUPER
    img = Image.new("L", (r - l + 2 * pad, b - t + 2 * pad), 0)
    ImageDraw.Draw(img).text((pad - l, pad - t), TEXT, font=font, fill=255)
    small = img.resize((img.width // SUPER, img.height // SUPER), Image.LANCZOS)
    return small.crop(small.getbbox())


def glow_of(alpha, radius, gain):
    """The shape blurred into a glow; the box grows by the glow."""
    pad = radius * 3
    big = Image.new("L", (alpha.width + 2 * pad, alpha.height + 2 * pad), 0)
    big.paste(alpha, (pad, pad))
    g = big.filter(ImageFilter.GaussianBlur(radius))
    g = g.point(lambda v: min(255, int(v * gain + 0.5)))
    box = g.point(lambda v: 255 if v >= 9 else 0).getbbox()   # what survives 4 bits
    return g.crop(box), pad - box[0], pad - box[1]


def to4(img):
    """8-bit -> 16 levels, two pixels a byte (high nibble first); rows padded to whole bytes."""
    w, h = img.size
    px = img.load()
    out = []
    for y in range(h):
        row = [(px[x, y] * 15 + 127) // 255 for x in range(w)]
        if w % 2:
            row.append(0)
        out += [(row[i] << 4) | row[i + 1] for i in range(0, len(row), 2)]
    return out


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("  " + ", ".join("0x%02X" % v for v in data[i:i + 24]) + ",")
    return "static const uint8_t %s[%d] = {\n%s\n};\n" % (name, len(data), "\n".join(lines))


def write_header(logo, glow, gx, gy):
    lx = (SCREEN_W - logo.width) // 2
    ly = LOGO_CY - logo.height // 2
    path = os.path.join(ROOT, "src", "logo_miasmora.h")
    with open(path, "w", newline="\n") as f:
        f.write("// MIASMORA -- the splash logo. GENERATED by tools/make_logo.py: do not edit.\n")
        f.write("// \"%s\" in UnifrakturMaguntia (j. 'mach' wust, after Peter Wiegel;\n" % TEXT)
        f.write("// SIL Open Font License 1.1, tools/fonts/OFL.txt). 4-bit alpha, two pixels a\n")
        f.write("// byte (high nibble = left), each row padded to a whole byte.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("static constexpr int LOGO_W = %d, LOGO_H = %d, LOGO_X = %d, LOGO_Y = %d;\n"
                % (logo.width, logo.height, lx, ly))
        f.write("static constexpr int GLOW_W = %d, GLOW_H = %d, GLOW_X = %d, GLOW_Y = %d;\n\n"
                % (glow.width, glow.height, lx - gx, ly - gy))
        f.write(c_array("LOGO_A4", to4(logo)))
        f.write("\n")
        f.write(c_array("GLOW_A4", to4(glow)))
    print("wrote", path, logo.size, "glow", glow.size)


# --- the promotional image (1280 x 960) -----------------------------------------
PROMO_W, PROMO_H = 1280, 960


def fog_field(w, h, seed):
    """Smooth noise 0..1: a coarse grid enlarged smoothly, plus a finer one (as on the device)."""
    rnd = random.Random(seed)
    coarse = Image.new("L", (13, 8))
    coarse.putdata([rnd.randrange(256) for _ in range(13 * 8)])
    fine = Image.new("L", (40, 24))
    fine.putdata([rnd.randrange(256) for _ in range(40 * 24)])
    a = coarse.resize((w, h), Image.BICUBIC)
    b = fine.resize((w, h), Image.BICUBIC)
    return Image.blend(a, b, 0.25)


def blend(c0, c1, t):
    return tuple(int(c0[i] + (c1[i] - c0[i]) * t + 0.5) for i in range(3))


def make_promo():
    W, H = PROMO_W, PROMO_H
    # fog: the background with a trace of the logo's colour
    fog = fog_field(W, H, 0x4D49).load()
    img = Image.new("RGB", (W, H))
    px = img.load()
    for y in range(H):
        for x in range(W):
            px[x, y] = blend(C_BG, C_ACC2, 0.10 * fog[x, y] / 255.0)
    # the logo, large, with its glow (as at the first heartbeat)
    logo = render_text(1060)
    glow, gx, gy = glow_of(logo, 22, 1.6)
    lx = (W - logo.width) // 2
    ly = 400 - logo.height // 2
    glow_rgb = Image.new("RGB", glow.size, C_ACC2)
    base = img.copy()
    img.paste(glow_rgb, (lx - gx, ly - gy), glow.point(lambda v: int(v * 0.55)))
    img = Image.blend(base, img, 1.0)
    bright = blend(C_ACC2, (255, 255, 255), 0.12)
    img.paste(Image.new("RGB", logo.size, bright), (lx, ly), logo)
    # the subtitle, spaced out, in the subtitle grey
    d = ImageDraw.Draw(img)
    sub = "DARK AMBIENT DRONE GENERATOR"
    font = ImageFont.load_default(size=34)
    spacing = 10
    widths = [d.textlength(ch, font=font) for ch in sub]
    total = sum(widths) + spacing * (len(sub) - 1)
    x = (W - total) / 2
    y = ly + logo.height + 110
    for ch, cw in zip(sub, widths):
        d.text((x, y), ch, font=font, fill=C_DIM)
        x += cw + spacing
    path = os.path.join(ROOT, "docs", "MIASMORA_promo_1280x960.png")
    img.save(path, optimize=True)
    print("wrote", path)


def main():
    logo = render_text(LOGO_WIDTH)
    glow, gx, gy = glow_of(logo, GLOW_RADIUS, GLOW_GAIN)
    write_header(logo, glow, gx, gy)
    make_promo()


if __name__ == "__main__":
    main()
